const {readFileSync} = require('node:fs');
const {join} = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = join(__dirname,'../..');
const base = readFileSync(join(root,'qml/Veyra/EffectSupport.js'),'utf8').replace(/^\.pragma library\s*/, '');
const extension = readFileSync(join(root,'scripts/radeon/player/Integration.js'),'utf8');
const context = vm.createContext({});
vm.runInContext(base+'\n'+extension,context);
const calls=[];
const caps={nr2:{available:true},sr0:{available:true},hdr:{available:true},dlss:{available:true}};
const ids={'nr':'nr2','sr':'sr0','video-hdr':'hdr','frame-generation':'dlss','sr0':'sr0'};
const api={effectCapabilities:caps,effectAvailability(id){calls.push(id);return caps[ids[id]] || {available:false,reason:'unsupported'};}};
const result=Object.fromEntries(Object.keys(ids).map(id=>[id,context.available(api,id)]));
console.log('effect menu availability:',JSON.stringify(result));
for(const id of Object.keys(ids)) assert.equal(result[id],true,id+' was incorrectly disabled');
assert.deepEqual(calls,Object.keys(ids),'The original bridge effect-ID mapping must be used');
caps.hdr={available:false,reason:'missing runtime'};
assert.equal(context.available(api,'video-hdr'),false);
assert.equal(context.reason(api,'video-hdr'),'missing runtime');
const functionNames=source=>[...source.matchAll(/^function\s+(\w+)\s*\(/gm)].map(m=>m[1]);
const duplicates=functionNames(extension).filter(name=>functionNames(base).includes(name));
assert.deepEqual(duplicates,[],'Extension must not replace existing EffectSupport functions');
console.log('PASS: composed production helper keeps NR/SR/HDR/FG gates and genuine unsupported reasons');
